export async function getVerifiedVideos(): Promise<ConstructionVideo[]> {
  const apiKey = process.env.YOUTUBE_API_KEY;
  const channelId = process.env.YOUTUBE_CHANNEL_ID || OFFICIAL_CHANNEL_ID;

  if (apiKey) {
    try {
      const res = await fetch(
        `https://www.googleapis.com/youtube/v3/search?key=${apiKey}&channelId=${channelId}&part=snippet,id&order=date&maxResults=25`,
        { next: { revalidate: 3600 } }
      );
      if (res.ok) {
        const data = await res.json();
        if (Array.isArray(data.items) && data.items.length > 0) {
          const verifiedItems = data.items
            .filter((item: any) => {
              // STRICT SOURCE LOCK: Must match official channel ID
              const returnedChannelId = item.snippet?.channelId;
              return !returnedChannelId || returnedChannelId === OFFICIAL_CHANNEL_ID;
            })
            .map((item: any) => {
              const videoId = item.id?.videoId || item.id;
              const title = item.snippet?.title || '';
              const isShort = title.toLowerCase().includes('short') || title.includes('❌') || false;
              return {
                id: videoId,
                title: title || 'CONSTRUCTIONS Video Update',
                description: item.snippet?.description || `Independent video update from ${OFFICIAL_CHANNEL_HANDLE}`,
                thumbnailUrl: item.snippet?.thumbnails?.high?.url || item.snippet?.thumbnails?.medium?.url || `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
                publishedAt: item.snippet?.publishedAt ? item.snippet.publishedAt.split('T')[0] : '2026-08-01',
                duration: isShort ? '0:59' : '06:15',
                isShort,
                embedUrl: `https://www.youtube-nocookie.com/embed/${videoId}`,
                youtubeUrl: isShort ? `https://www.youtube.com/shorts/${videoId}` : `https://www.youtube.com/watch?v=${videoId}`,
                category: isShort ? ('CONSTRUCTION_PROGRESS' as const) : ('MARKET_OVERVIEW' as const),
                channelId: OFFICIAL_CHANNEL_ID,
                channelTitle: OFFICIAL_CHANNEL_NAME
              };
            });

          if (verifiedItems.length > 0) {
            return verifiedItems;
          }
        }
      }
    } catch (e) {
      console.error('[YouTube Fetch Exception]', e);
    }
  }

  // Fallback ONLY to verified official channel items
  return REAL_CONSTRUCTIONS_VIDEOS;
}
