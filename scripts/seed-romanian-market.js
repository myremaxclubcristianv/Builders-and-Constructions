// Seed Function
async function seedFullDatabase() {
  console.log('Seeding locations...');
  const locationMap = new Map();
  for (const loc of realLocations) {
    const { data, error } = await supabase.from('locations').upsert(loc, { onConflict: 'slug' }).select().single();
    if (error) console.error(`Location ${loc.slug} error:`, error.message);
    else if (data) locationMap.set(data.slug, data.id);
  }
  console.log(`Locations seeded: ${locationMap.size}`);

  console.log('Seeding companies...');
  const companyMap = new Map();
  for (const comp of realCompanies) {
    const locId = locationMap.get(comp.location_slug);
    const dbPayload = {
      name: comp.name,
      slug: comp.slug,
      type: comp.type,
      location_id: locId,
      description: comp.description,
      founded_year: comp.founded_year,
      website: comp.website,
      specializations: comp.specializations,
      services: comp.services,
      markets: comp.markets,
      certifications: comp.certifications,
      is_featured: comp.is_featured,
      website_verification: comp.website_verification,
      published_at: comp.published_at
    };
    const { data, error } = await supabase.from('companies').upsert(dbPayload, { onConflict: 'slug' }).select().single();
    if (error) console.error(`Company ${comp.slug} error:`, error.message);
    else if (data) companyMap.set(data.slug, data.id);
  }
  console.log(`Companies seeded: ${companyMap.size}`);

  console.log('Database master seeding completed.');
}

seedFullDatabase();
